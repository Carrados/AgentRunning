// Builds worker.js from site/index.html so the Worker serves the page with no separate asset upload.
import { readFileSync, writeFileSync } from 'node:fs';
const html = readFileSync(new URL('../site/index.html', import.meta.url), 'utf8');
const worker = `// Generated by scripts/build-worker.mjs from site/index.html. Do not edit by hand.
const HTML = ${JSON.stringify(html)};
export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (url.hostname.startsWith('www.')) {
      url.hostname = url.hostname.slice(4);
      return Response.redirect(url.toString(), 301);
    }
    if (url.pathname !== '/' && url.pathname !== '/index.html') {
      return new Response(HTML, { status: 404, headers: { 'content-type': 'text/html; charset=utf-8' } });
    }
    return new Response(HTML, { headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'public, max-age=300' } });
  }
};
`;
writeFileSync(new URL('../worker.js', import.meta.url), worker);
console.log('worker.js', worker.length, 'bytes');
